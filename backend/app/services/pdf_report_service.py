import io
from typing import Dict, Any
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

class PDFReportService:
    @staticmethod
    def generate_property_pdf_report(prop_data: Dict[str, Any], ai_analytics: Dict[str, Any]) -> bytes:
        """Generate a downloadable PDF valuation and spatial report using ReportLab."""
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=36,
            leftMargin=36,
            topMargin=36,
            bottomMargin=36
        )

        styles = getSampleStyleSheet()
        
        title_style = ParagraphStyle(
            'ReportTitle',
            parent=styles['Heading1'],
            fontName='Helvetica-Bold',
            fontSize=22,
            leading=26,
            textColor=colors.HexColor('#0284c7')
        )
        
        subtitle_style = ParagraphStyle(
            'ReportSubTitle',
            parent=styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=11,
            leading=14,
            textColor=colors.HexColor('#475569')
        )

        heading_style = ParagraphStyle(
            'SectionHeading',
            parent=styles['Heading2'],
            fontName='Helvetica-Bold',
            fontSize=14,
            leading=18,
            textColor=colors.HexColor('#0f172a'),
            spaceBefore=12,
            spaceAfter=6
        )

        body_style = ParagraphStyle(
            'ReportBody',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=10,
            leading=14,
            textColor=colors.HexColor('#1e293b')
        )

        elements = []

        # 1. Header Banner
        elements.append(Paragraph("Real Estate AI - Property Valuation & Spatial GIS Report", title_style))
        elements.append(Paragraph("Generated by Bangalore Real Estate Intelligence Engine", subtitle_style))
        elements.append(Spacer(1, 10))
        elements.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#0284c7'), spaceAfter=15))

        # 2. Property Overview Table
        elements.append(Paragraph("1. Property Overview", heading_style))
        overview_data = [
            [Paragraph("<b>Property Name</b>", body_style), Paragraph(str(prop_data.get("title", "")), body_style)],
            [Paragraph("<b>Property Type & BHK</b>", body_style), Paragraph(f"{prop_data.get('property_type', '')} - {prop_data.get('bhk', '')} BHK", body_style)],
            [Paragraph("<b>Super Built-up Area</b>", body_style), Paragraph(f"{prop_data.get('area_sqft', '')} Sq.ft", body_style)],
            [Paragraph("<b>Locality Address</b>", body_style), Paragraph(str(prop_data.get("address", "")), body_style)],
            [Paragraph("<b>Expected Asking Price</b>", body_style), Paragraph(str(prop_data.get("price_formatted", "")), body_style)],
        ]
        t_overview = Table(overview_data, colWidths=[150, 380])
        t_overview.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#f8fafc')),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
            ('PADDING', (0, 0), (-1, -1), 6),
        ]))
        elements.append(t_overview)
        elements.append(Spacer(1, 15))

        # 3. AI Valuation & Price Prediction
        val = ai_analytics.get("price_prediction", {})
        elements.append(Paragraph("2. AI Valuation & Price Prediction", heading_style))
        val_data = [
            [Paragraph("<b>AI Predicted Selling Price</b>", body_style), Paragraph(f"₹{int(val.get('predicted_selling_price', 0)):,}", body_style)],
            [Paragraph("<b>Estimated Monthly Rental Value</b>", body_style), Paragraph(f"₹{int(val.get('estimated_rental_price', 0)):,}/month", body_style)],
            [Paragraph("<b>Predicted Rate per Sq.ft</b>", body_style), Paragraph(f"₹{val.get('price_per_sqft', 0):,}/sq.ft", body_style)],
            [Paragraph("<b>Prediction Confidence Score</b>", body_style), Paragraph(f"{val.get('confidence_score', 0)}%", body_style)],
        ]
        t_val = Table(val_data, colWidths=[180, 350])
        t_val.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#f0f9ff')),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#bae6fd')),
            ('PADDING', (0, 0), (-1, -1), 6),
        ]))
        elements.append(t_val)
        elements.append(Spacer(1, 15))

        # 4. Computer Vision & NLP Analysis
        cv = ai_analytics.get("image_ai", {})
        nlp = ai_analytics.get("text_ai", {})
        safety = ai_analytics.get("safety_guard", {})
        elements.append(Paragraph("3. Computer Vision & Safety Guard Metrics", heading_style))
        ai_data = [
            [Paragraph("<b>Image Quality & Condition (OpenCV)</b>", body_style), Paragraph(f"{cv.get('overall_score', 80)}/100 ({cv.get('overall_condition', 'Good')})", body_style)],
            [Paragraph("<b>Description NLP Quality Score</b>", body_style), Paragraph(f"{nlp.get('text_quality_score', 75)}/100", body_style)],
            [Paragraph("<b>Locality Safety Score</b>", body_style), Paragraph(f"{safety.get('safety_score', 90)}/100 (Grade {safety.get('overall_rating', 'A')})", body_style)],
            [Paragraph("<b>Flood Risk Status</b>", body_style), Paragraph(str(safety.get("flood_risk", "Low Risk")), body_style)],
        ]
        t_ai = Table(ai_data, colWidths=[200, 330])
        t_ai.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#f8fafc')),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
            ('PADDING', (0, 0), (-1, -1), 6),
        ]))
        elements.append(t_ai)
        elements.append(Spacer(1, 15))

        # 5. SHAP Explainability
        shap = val.get("shap_explanation", {})
        pos_factors = ", ".join([f['factor'] for f in shap.get("top_positive_factors", [])]) or "Proximity to Metro and Prime Hub"
        elements.append(Paragraph("4. SHAP Feature Valuation Attribution", heading_style))
        elements.append(Paragraph(f"<b>Key Value Drivers:</b> {pos_factors}", body_style))

        doc.build(elements)
        pdf_bytes = buffer.getvalue()
        buffer.close()
        return pdf_bytes
